void UpgradeFirmware(const char *url) {
    // Expand the watchdog time as the flash write is slow.
    #if ESP_IDF_VERSION_MAJOR >= 5
        esp_task_wdt_config_t wdtc;
        wdtc.timeout_ms = 60000;
        wdtc.idle_core_mask = 0;
        wdtc.trigger_panic = false;
        esp_task_wdt_reconfigure(&wdtc);
    #else
        esp_task_wdt_init(60, false);
    #endif

    esp_http_client_config_t http_config = {
        .url = url,
        .cert_pem = cacertpem,
        .transport_type = HTTP_TRANSPORT_OVER_SSL,
    };

    esp_https_ota_config_t ota_config = {
        .http_config = &http_config,
    };

    esp_err_t ret = esp_https_ota(&ota_config);
    ESP_LOGI("ota", "Starting firmware update");
    if (ret == ESP_OK) {
        esp_restart();
        return; // never reached in theory.
    } else {
        ESP_LOGE("ota", "Firmware upgrade failed");
    }

    // Set the WDT back to the configured timeout if the upgrade failed.
    #if ESP_IDF_VERSION_MAJOR >= 5
        wdtc.timeout_ms = CONFIG_ESP_TASK_WDT_TIMEOUT_S;
        esp_task_wdt_reconfigure(&wdtc);
    #else
        esp_task_wdt_init(CONFIG_ESP_TASK_WDT_TIMEOUT_S, false);
    #endif
}

void FirmwareInfo() {
    const esp_partition_t *part_info = esp_ota_get_running_partition();
    ESP_LOGI("ota", "Firmware (%s) running from %s", App.get_compilation_time().c_str(), part_info->label);
}